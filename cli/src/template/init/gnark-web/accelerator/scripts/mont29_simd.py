#!/usr/bin/env python3
"""Writes src/mont29_simd.s: four Montgomery multiplications at once, for
BN254 Fq and Fr, in WebAssembly SIMD.

The algorithm is ark-bn254/src/mont29.rs's (eight radix-2^29 CIOS
reductions and one radix-2^24 reduction), on four independent products:
limb j of the four operands lies in one u32x4, and each running limb is two
u64x2 (products 0 and 1, products 2 and 3). It is written as assembly
because LLVM rewrites the widening multiplies (i64x2.extmul_*_i32x4_u) into
extends and i64x2.mul, which engines emulate. The accumulator registers
rotate instead of moving. It lives in this crate, the cdylib: in a
dependency built for LTO, LLVM parses module assembly without the SIMD
target feature.

    mont29_mul4_<field>(x: *const [u32x4; 9], y: *const [u32x4; 9], out: *mut [u32x4; 10])

out holds the normalized 29-bit limbs t0..t9 of the four results, before
ark-bn254/src/mont29.rs's final shift and conditional subtraction.

    python3 scripts/mont29_simd.py > src/mont29_simd.s
"""

MASK = (1 << 29) - 1
FIELDS = {
    "fq": (0x30644E72E131A029B85045B68181585D97816A916871CA8D3C208C16D87CFD47, 0x87D20782E4866389),
    "fr": (0x30644E72E131A029B85045B68181585D2833E84879B9709143E1F593F0000001, 0xC2E1F593EFFFFFFF),
}
NARROW = "0, 1, 2, 3, 8, 9, 10, 11, 16, 17, 18, 19, 24, 25, 26, 27"


def signed32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v >= 1 << 31 else v


def function(name, modulus, inv):
    limbs = [(modulus >> (29 * j)) & MASK for j in range(9)]
    # Locals 0-2 are the parameters.
    x = [3 + j for j in range(9)]
    y = [12 + j for j in range(9)]
    p = [21 + j for j in range(9)]
    lo = [30 + j for j in range(10)]
    hi = [40 + j for j in range(10)]
    q, zero, mask = 50, 51, 52
    out = []
    e = out.append
    e(f"\t.globl\t{name}")
    e(f"\t.type\t{name},@function")
    e(f"{name}:")
    e(f"\t.functype\t{name} (i32, i32, i32) -> ()")
    e("\t.local\t" + ", ".join(["v128"] * 50))
    for j in range(9):
        e(f"\tlocal.get\t0\n\tv128.load\t{16 * j}\n\tlocal.set\t{x[j]}")
        e(f"\tlocal.get\t1\n\tv128.load\t{16 * j}\n\tlocal.set\t{y[j]}")
        e(f"\ti32.const\t{limbs[j]}\n\ti32x4.splat\n\tlocal.set\t{p[j]}")
    e(f"\ti64.const\t0\n\ti64x2.splat\n\tlocal.set\t{zero}")
    e(f"\ti64.const\t{MASK}\n\ti64x2.splat\n\tlocal.set\t{mask}")
    for j in range(10):
        e(f"\tlocal.get\t{zero}\n\tlocal.set\t{lo[j]}\n\tlocal.get\t{zero}\n\tlocal.set\t{hi[j]}")

    def accumulate(target, a, b, half):
        e(f"\tlocal.get\t{target}\n\tlocal.get\t{a}\n\tlocal.get\t{b}")
        e(f"\ti64x2.extmul_{half}_i32x4_u\n\ti64x2.add\n\tlocal.set\t{target}")

    shift = 0
    for i in range(9):
        l = lambda k: lo[(k + shift) % 10]
        h = lambda k: hi[(k + shift) % 10]
        for j in range(9):
            accumulate(l(j), x[j], y[i], "low")
            accumulate(h(j), x[j], y[i], "high")
        # q = t0 * inv mod 2^29 (2^24 for the last reduction), per product.
        width = (1 << 24) - 1 if i == 8 else MASK
        e(f"\tlocal.get\t{l(0)}\n\tlocal.get\t{h(0)}\n\ti8x16.shuffle\t{NARROW}")
        e(f"\ti32.const\t{signed32(inv)}\n\ti32x4.splat\n\ti32x4.mul")
        e(f"\ti32.const\t{width}\n\ti32x4.splat\n\tv128.and\n\tlocal.set\t{q}")
        for j in range(9):
            accumulate(l(j), q, p[j], "low")
            accumulate(h(j), q, p[j], "high")
        if i < 8:
            for limb in (l, h):
                e(f"\tlocal.get\t{limb(1)}\n\tlocal.get\t{limb(0)}\n\ti32.const\t29\n\ti64x2.shr_u\n\ti64x2.add\n\tlocal.set\t{limb(1)}")
                # The consumed limb becomes the next top limb, which starts at zero.
                e(f"\tlocal.get\t{zero}\n\tlocal.set\t{limb(0)}")
            shift += 1
    for limb in (lambda k: lo[(k + shift) % 10], lambda k: hi[(k + shift) % 10]):
        for j in range(9):
            e(f"\tlocal.get\t{limb(j + 1)}\n\tlocal.get\t{limb(j)}\n\ti32.const\t29\n\ti64x2.shr_u\n\ti64x2.add\n\tlocal.set\t{limb(j + 1)}")
            e(f"\tlocal.get\t{limb(j)}\n\tlocal.get\t{mask}\n\tv128.and\n\tlocal.set\t{limb(j)}")
    for j in range(10):
        e(f"\tlocal.get\t2\n\tlocal.get\t{lo[(j + shift) % 10]}\n\tlocal.get\t{hi[(j + shift) % 10]}")
        e(f"\ti8x16.shuffle\t{NARROW}\n\tv128.store\t{16 * j}")
    e("\tend_function")
    return "\n".join(out)


print("# Generated by scripts/mont29_simd.py; do not edit.")
for field, (modulus, inv) in FIELDS.items():
    print(function(f"mont29_mul4_{field}", modulus, inv))
